// **así** se muestra en negrita, ~así~ en cursiva.
// Si a un idioma le falta una clave, se usa la de español.

import FEATURE_STRINGS from './i18n-features';

export const LANGUAGES = [
  { code: 'es', label: 'Español' },
  { code: 'en', label: 'English' },
  { code: 'it', label: 'Italiano' },
];
export const LANG_STORAGE = 'app-lang-v1';

let currentLang = 'es';
export const setCurrentLang = (lang) => { currentLang = STRINGS[lang] ? lang : 'es'; };
export const getLang = () => currentLang;

// Idioma inicial: el que se eligió antes en este dispositivo, o el del navegador si es uno
// de los tres, o español.
export const detectInitialLang = () => {
  try {
    const saved = localStorage.getItem(LANG_STORAGE);
    if (saved && STRINGS[saved]) return saved;
  } catch (e) { /* noop */ }
  try {
    const prefs = (navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language]) || [];
    for (const p of prefs) {
      const code = String(p || '').slice(0, 2).toLowerCase();
      if (STRINGS[code]) return code;
    }
  } catch (e) { /* noop */ }
  return 'es';
};

const lookup = (lang, key) => {
  const base = STRINGS[lang];
  if (base && base[key] !== undefined) return base[key];
  const extra = FEATURE_STRINGS[lang];
  if (extra && extra[key] !== undefined) return extra[key];
  return undefined;
};

export const tr = (key, vars) => {
  let text = lookup(currentLang, key);
  if (text === undefined) text = lookup('es', key);
  if (text === undefined) return key;
  if (vars) {
    Object.keys(vars).forEach((k) => {
      text = text.split(`{${k}}`).join(String(vars[k]));
    });
  }
  return text;
};

// Singular/plural: usa clave_one o clave_other según n.
export const trn = (key, n, vars) => tr(`${key}_${n === 1 ? 'one' : 'other'}`, { n, ...(vars || {}) });

